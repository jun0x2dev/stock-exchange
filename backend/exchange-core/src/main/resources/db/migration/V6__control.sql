-- 통제: DB 계정 분리, 감사 로그 체인, 원장 정정 승인.

ALTER TABLE users DROP CONSTRAINT users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('CUSTOMER', 'OPERATOR', 'APPROVER', 'AUDITOR'));

-- 감사 로그 체인. 행마다 앞 행의 해시를 포함해 HMAC을 계산한다. 키는 DB에 두지 않는다.
CREATE TABLE audit_chain (
    chain_seq BIGINT      PRIMARY KEY CHECK (chain_seq > 0),
    audit_id  BIGINT      NOT NULL UNIQUE REFERENCES audit_log,
    prev_hash VARCHAR(64) NOT NULL,
    hash      VARCHAR(64) NOT NULL
);
CREATE TRIGGER append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON audit_chain EXECUTE FUNCTION reject_modification();

-- 아직 체인에 넣지 않은 감사 로그. 커밋 순서와 번호 순서가 다를 수 있어 번호 범위로는 찾을 수 없다.
CREATE TABLE audit_pending (
    audit_id BIGINT PRIMARY KEY
);
INSERT INTO audit_pending SELECT audit_id FROM audit_log;
CREATE FUNCTION enqueue_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO audit_pending VALUES (NEW.audit_id);
    RETURN NEW;
END $$;
CREATE TRIGGER enqueue_audit AFTER INSERT ON audit_log FOR EACH ROW EXECUTE FUNCTION enqueue_audit();

-- 원장 정정. 입금·입고 전표를 반대 전표로 되돌린다. 요청자는 승인할 수 없다.
CREATE TABLE ledger_adjustment (
    adjustment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deposit_id    BIGINT       NOT NULL REFERENCES deposit,
    reason        VARCHAR(200) NOT NULL CHECK (length(trim(reason)) > 0),
    status        VARCHAR(20)  NOT NULL DEFAULT 'REQUESTED' CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED')),
    requested_by  BIGINT       NOT NULL REFERENCES users,
    decided_by    BIGINT       REFERENCES users,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    decided_at    TIMESTAMPTZ,
    CHECK ((status = 'REQUESTED') = (decided_by IS NULL)),
    CHECK ((decided_by IS NULL) = (decided_at IS NULL)),
    CHECK (decided_by <> requested_by)
);
-- 한 전표는 한 번만 정정한다. 거절된 요청은 다시 낼 수 있다.
CREATE UNIQUE INDEX uq_adjustment_deposit ON ledger_adjustment (deposit_id) WHERE status <> 'REJECTED';

ALTER TABLE cash_ledger DROP CONSTRAINT cash_ledger_type_check;
ALTER TABLE cash_ledger ADD CONSTRAINT cash_ledger_type_check
    CHECK (type IN ('DEPOSIT', 'RESERVE', 'RELEASE', 'BUY', 'SELL', 'REVERSAL'));
ALTER TABLE cash_ledger DROP CONSTRAINT cash_ledger_ref_type_check;
ALTER TABLE cash_ledger ADD CONSTRAINT cash_ledger_ref_type_check
    CHECK (ref_type IN ('ORDER', 'EXECUTION', 'DEPOSIT', 'ADJUSTMENT'));
ALTER TABLE position_ledger DROP CONSTRAINT position_ledger_type_check;
ALTER TABLE position_ledger ADD CONSTRAINT position_ledger_type_check
    CHECK (type IN ('DEPOSIT', 'RESERVE', 'RELEASE', 'BUY', 'SELL', 'REVERSAL'));
ALTER TABLE position_ledger DROP CONSTRAINT position_ledger_ref_type_check;
ALTER TABLE position_ledger ADD CONSTRAINT position_ledger_ref_type_check
    CHECK (ref_type IN ('ORDER', 'EXECUTION', 'DEPOSIT', 'ADJUSTMENT'));

-- 계정 분리. 이 마이그레이션을 실행하는 계정이 소유자이고, 애플리케이션은 exchange_app으로만 접속한다.
-- 비밀번호는 afterMigrate.sql이 환경 변수 값으로 맞춘다.
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'exchange_app') THEN
        CREATE ROLE exchange_app LOGIN;
    END IF;
    -- 조회용. 감사 담당자의 개인 계정에 이 역할을 준다.
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'exchange_readonly') THEN
        CREATE ROLE exchange_readonly NOLOGIN;
    END IF;
    EXECUTE format('REVOKE ALL ON DATABASE %I FROM PUBLIC', current_database());
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO exchange_app, exchange_readonly', current_database());
END $$;
GRANT USAGE ON SCHEMA public TO exchange_app, exchange_readonly;

-- 원장, 체결, 감사 기록은 추가만 할 수 있다.
GRANT SELECT, INSERT ON cash_ledger, position_ledger, execution, audit_log, audit_chain, deposit TO exchange_app;
GRANT SELECT, INSERT, DELETE ON audit_pending TO exchange_app;
-- 바꿀 수 있는 컬럼만 연다. 주문의 가격·수량, 계좌의 주인, 사용자의 역할과 비밀번호는 만든 뒤에 바꿀 수 없다.
GRANT SELECT, INSERT ON users, account, position, orders, outbox, ledger_adjustment TO exchange_app;
GRANT UPDATE (failed_count, locked_until) ON users TO exchange_app;
GRANT UPDATE (cash_balance, reserved_cash) ON account TO exchange_app;
GRANT UPDATE (quantity, reserved_quantity, total_cost, realized_pnl) ON position TO exchange_app;
GRANT UPDATE (filled_quantity, reserved_amount, status, engine_seq, cancel_requested_at) ON orders TO exchange_app;
GRANT UPDATE (published_at) ON outbox TO exchange_app;
GRANT UPDATE (status, decided_by, decided_at) ON ledger_adjustment TO exchange_app;
GRANT SELECT ON stock, invariant_violation TO exchange_app;
GRANT UPDATE (status, last_event_seq, halt_partition, halt_offset) ON stock TO exchange_app;
GRANT USAGE ON SEQUENCE journal_seq TO exchange_app;

GRANT SELECT ON account, position, orders, execution, deposit, cash_ledger, position_ledger, stock, outbox, audit_log,
    audit_chain, ledger_adjustment, invariant_violation TO exchange_readonly;
GRANT SELECT (user_id, login_id, role) ON users TO exchange_readonly;
