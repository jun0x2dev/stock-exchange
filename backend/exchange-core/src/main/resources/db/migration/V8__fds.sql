-- 이상거래 탐지(규칙 기반). 경보는 추가만 하고 지우지 않는다.

CREATE TABLE fds_alert (
    alert_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule        VARCHAR(20)  NOT NULL CHECK (rule IN ('SPOOFING')),
    -- 같은 사건을 두 번 경보하지 않도록 규칙마다 정하는 키. 허수성 호가는 주문 번호다.
    dedupe_key  VARCHAR(100) NOT NULL,
    account_id  BIGINT       NOT NULL REFERENCES account,
    symbol      VARCHAR(12)  REFERENCES stock,
    order_id    BIGINT       REFERENCES orders,
    evidence    VARCHAR(300) NOT NULL,
    detected_at TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (rule, dedupe_key)
);
CREATE INDEX idx_fds_alert_account ON fds_alert (account_id, alert_id DESC);
CREATE TRIGGER append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON fds_alert EXECUTE FUNCTION reject_modification();

-- 탐지 작업자가 최근에 취소된 주문과, 그 주문이 들어온 순간의 같은 쪽 호가 잔량을 읽는다.
CREATE INDEX idx_orders_canceled ON orders (updated_at) WHERE status = 'CANCELED';
CREATE INDEX idx_orders_side_created ON orders (symbol, side, created_at);

GRANT SELECT, INSERT ON fds_alert TO exchange_app;
GRANT SELECT ON fds_alert TO exchange_readonly;
