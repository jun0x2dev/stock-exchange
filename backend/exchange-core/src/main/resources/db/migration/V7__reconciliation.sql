-- 일 단위 대사. 실행 이력과 불일치 내역은 추가만 하고 지우지 않는다(5년 보존 대상).

CREATE TABLE reconciliation_run (
    run_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 대사로 마감하는 날짜(한국 시간). 정기 실행은 전날, 수동 실행은 실행한 날이다.
    business_date        DATE        NOT NULL,
    trigger              VARCHAR(10) NOT NULL CHECK (trigger IN ('SCHEDULED', 'MANUAL')),
    requested_by         BIGINT      REFERENCES users,
    status               VARCHAR(10) NOT NULL CHECK (status IN ('PASSED', 'FAILED')),
    invariant_violations INT         NOT NULL CHECK (invariant_violations >= 0),
    audit_problems       INT         NOT NULL CHECK (audit_problems >= 0),
    audit_checked        BIGINT      NOT NULL CHECK (audit_checked >= 0),
    started_at           TIMESTAMPTZ NOT NULL,
    finished_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CHECK ((trigger = 'SCHEDULED') = (requested_by IS NULL)),
    CHECK ((status = 'PASSED') = (invariant_violations = 0 AND audit_problems = 0))
);
-- 정기 대사는 날짜마다 한 번만 기록한다. 여러 서버가 동시에 실행해도 같다.
CREATE UNIQUE INDEX uq_reconciliation_scheduled ON reconciliation_run (business_date) WHERE trigger = 'SCHEDULED';
CREATE INDEX idx_reconciliation_run_date ON reconciliation_run (business_date DESC, run_id DESC);

CREATE TABLE reconciliation_violation (
    violation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       BIGINT       NOT NULL REFERENCES reconciliation_run,
    kind         VARCHAR(10)  NOT NULL CHECK (kind IN ('I1', 'I2', 'I3', 'I4', 'I5', 'I6', 'I7', 'AUDIT')),
    detail       VARCHAR(200) NOT NULL
);
CREATE INDEX idx_reconciliation_violation_run ON reconciliation_violation (run_id, violation_id);

CREATE TRIGGER append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON reconciliation_run
    EXECUTE FUNCTION reject_modification();
CREATE TRIGGER append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON reconciliation_violation
    EXECUTE FUNCTION reject_modification();

GRANT SELECT, INSERT ON reconciliation_run, reconciliation_violation TO exchange_app;
GRANT SELECT ON reconciliation_run, reconciliation_violation TO exchange_readonly;
