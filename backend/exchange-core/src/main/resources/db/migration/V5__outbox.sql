-- 2단계: 매칭 엔진을 별도 프로세스로 분리한다.
-- 엔진은 명령 토픽을 처음부터 다시 처리해 호가창을 만들므로, 명령 기록이 없는 1단계 주문은 이어받을 수 없다.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM orders) THEN
        RAISE EXCEPTION '1단계 주문이 남아 있다. 빈 DB에서 시작해야 한다 (docker compose down -v)';
    END IF;
END $$;

-- 엔진에 보낼 명령. 주문과 같은 트랜잭션에서 저장하고, 발행기가 Kafka로 옮긴다.
CREATE TABLE outbox (
    command_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(10) NOT NULL CHECK (type IN ('PLACE', 'CANCEL')),
    symbol       VARCHAR(12) NOT NULL REFERENCES stock,
    order_id     BIGINT      NOT NULL REFERENCES orders,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    published_at TIMESTAMPTZ,
    UNIQUE (order_id, type)
);
CREATE INDEX idx_outbox_unpublished ON outbox (command_id) WHERE published_at IS NULL;

-- 종목을 멈췄을 때 반영하지 못한 첫 이벤트의 위치. 정지를 풀고 재시작하면 여기서부터 다시 읽는다.
ALTER TABLE stock ADD COLUMN halt_partition INT;
ALTER TABLE stock ADD COLUMN halt_offset BIGINT;
ALTER TABLE stock ADD CHECK ((halt_partition IS NULL) = (halt_offset IS NULL));

-- 1단계에서 DB를 명령 큐로 쓸 때만 필요했던 인덱스.
DROP INDEX idx_orders_accepted;
DROP INDEX idx_orders_cancel;
DROP INDEX idx_orders_book;
CREATE INDEX idx_orders_book ON orders (symbol, side, price) WHERE status IN ('OPEN', 'PARTIALLY_FILLED');
