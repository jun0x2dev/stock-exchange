-- 1단계 스키마. 불변식 중 DB로 막을 수 있는 것은 CHECK·UNIQUE로도 막는다.

CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('CUSTOMER', 'OPERATOR')),
    failed_count  INT          NOT NULL DEFAULT 0,
    locked_until  TIMESTAMPTZ
);

CREATE TABLE account (
    account_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT REFERENCES users,
    account_type  VARCHAR(20) NOT NULL CHECK (account_type IN ('CUSTOMER', 'EXTERNAL')),
    cash_balance  BIGINT      NOT NULL DEFAULT 0,
    reserved_cash BIGINT      NOT NULL DEFAULT 0,
    CHECK (reserved_cash >= 0 AND reserved_cash <= cash_balance),
    CHECK ((account_type = 'CUSTOMER') = (user_id IS NOT NULL))
);
CREATE INDEX idx_account_user ON account (user_id);
-- 외부 입출금·입고의 상대 계정은 하나만 둔다.
CREATE UNIQUE INDEX uq_account_external ON account (account_type) WHERE account_type = 'EXTERNAL';
INSERT INTO account (account_type) VALUES ('EXTERNAL');

CREATE TABLE stock (
    symbol         VARCHAR(12)  PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    base_price     BIGINT       NOT NULL CHECK (base_price > 0),
    status         VARCHAR(20)  NOT NULL DEFAULT 'TRADABLE' CHECK (status IN ('TRADABLE', 'HALTED')),
    last_event_seq BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE position (
    account_id        BIGINT      NOT NULL REFERENCES account,
    symbol            VARCHAR(12) NOT NULL REFERENCES stock,
    quantity          BIGINT      NOT NULL DEFAULT 0,
    reserved_quantity BIGINT      NOT NULL DEFAULT 0,
    total_cost        BIGINT      NOT NULL DEFAULT 0 CHECK (total_cost >= 0),
    realized_pnl      BIGINT      NOT NULL DEFAULT 0,
    PRIMARY KEY (account_id, symbol),
    CHECK (reserved_quantity >= 0 AND reserved_quantity <= quantity),
    CHECK (quantity > 0 OR total_cost = 0)
);

CREATE TABLE deposit (
    deposit_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT      NOT NULL REFERENCES account,
    symbol          VARCHAR(12) REFERENCES stock,
    amount          BIGINT      NOT NULL CHECK (amount > 0),
    idempotency_key VARCHAR(64) NOT NULL,
    request_hash    VARCHAR(64) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (account_id, idempotency_key)
);
COMMENT ON COLUMN deposit.symbol IS '주식 입고일 때만 값이 있고, 이때 amount는 수량이다';

CREATE TABLE orders (
    order_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT      NOT NULL REFERENCES account,
    symbol              VARCHAR(12) NOT NULL REFERENCES stock,
    side                VARCHAR(4)  NOT NULL CHECK (side IN ('BUY', 'SELL')),
    price               BIGINT      NOT NULL CHECK (price > 0),
    quantity            BIGINT      NOT NULL CHECK (quantity > 0),
    filled_quantity     BIGINT      NOT NULL DEFAULT 0 CHECK (filled_quantity BETWEEN 0 AND quantity),
    reserved_amount     BIGINT      NOT NULL DEFAULT 0,
    status              VARCHAR(20) NOT NULL DEFAULT 'ACCEPTED'
        CHECK (status IN ('ACCEPTED', 'OPEN', 'PARTIALLY_FILLED', 'FILLED', 'CANCELED')),
    engine_seq          BIGINT,
    cancel_requested_at TIMESTAMPTZ,
    idempotency_key     VARCHAR(64) NOT NULL,
    request_hash        VARCHAR(64) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (account_id, idempotency_key),
    UNIQUE (symbol, engine_seq),
    CHECK ((status = 'ACCEPTED') = (engine_seq IS NULL)),
    CHECK ((status = 'FILLED') = (filled_quantity = quantity)),
    -- 예약금은 미체결 매수의 남은 수량만큼만 존재한다.
    CHECK (reserved_amount = CASE
        WHEN side = 'BUY' AND status IN ('ACCEPTED', 'OPEN', 'PARTIALLY_FILLED')
        THEN price * (quantity - filled_quantity) ELSE 0 END)
);
CREATE INDEX idx_orders_account ON orders (account_id, order_id DESC);
CREATE INDEX idx_orders_accepted ON orders (symbol, order_id) WHERE status = 'ACCEPTED';
CREATE INDEX idx_orders_book ON orders (symbol, engine_seq) WHERE status IN ('OPEN', 'PARTIALLY_FILLED');
CREATE INDEX idx_orders_cancel ON orders (symbol, cancel_requested_at)
    WHERE cancel_requested_at IS NOT NULL AND status IN ('OPEN', 'PARTIALLY_FILLED');

CREATE TABLE execution (
    execution_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol        VARCHAR(12) NOT NULL REFERENCES stock,
    event_seq     BIGINT      NOT NULL,
    buy_order_id  BIGINT      NOT NULL REFERENCES orders,
    sell_order_id BIGINT      NOT NULL REFERENCES orders,
    price         BIGINT      NOT NULL CHECK (price > 0),
    quantity      BIGINT      NOT NULL CHECK (quantity > 0),
    executed_at   TIMESTAMPTZ NOT NULL,
    UNIQUE (symbol, event_seq)
);
CREATE INDEX idx_execution_buy ON execution (buy_order_id);
CREATE INDEX idx_execution_sell ON execution (sell_order_id);

CREATE SEQUENCE journal_seq;

CREATE TABLE cash_ledger (
    ledger_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id     BIGINT      NOT NULL,
    account_id     BIGINT      NOT NULL REFERENCES account,
    type           VARCHAR(20) NOT NULL CHECK (type IN ('DEPOSIT', 'RESERVE', 'RELEASE', 'BUY', 'SELL')),
    cash_delta     BIGINT      NOT NULL,
    reserved_delta BIGINT      NOT NULL,
    ref_type       VARCHAR(20) NOT NULL CHECK (ref_type IN ('ORDER', 'EXECUTION', 'DEPOSIT')),
    ref_id         BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    UNIQUE (account_id, type, ref_type, ref_id)
);
CREATE INDEX idx_cash_ledger_account ON cash_ledger (account_id, ledger_id DESC);

CREATE TABLE position_ledger (
    ledger_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id     BIGINT      NOT NULL,
    account_id     BIGINT      NOT NULL REFERENCES account,
    symbol         VARCHAR(12) NOT NULL REFERENCES stock,
    type           VARCHAR(20) NOT NULL CHECK (type IN ('DEPOSIT', 'RESERVE', 'RELEASE', 'BUY', 'SELL')),
    quantity_delta BIGINT      NOT NULL,
    reserved_delta BIGINT      NOT NULL,
    ref_type       VARCHAR(20) NOT NULL CHECK (ref_type IN ('ORDER', 'EXECUTION', 'DEPOSIT')),
    ref_id         BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    UNIQUE (account_id, symbol, type, ref_type, ref_id)
);

CREATE TABLE audit_log (
    audit_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT,
    ip         VARCHAR(45),
    action     VARCHAR(100) NOT NULL,
    target     VARCHAR(100),
    result     VARCHAR(50)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp()
);

-- 원장·체결·감사 로그는 INSERT만 허용한다. DB 계정 권한 분리(3단계) 전까지는 트리거가 막는다.
CREATE FUNCTION reject_modification() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END $$;
CREATE TRIGGER append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON cash_ledger EXECUTE FUNCTION reject_modification();
CREATE TRIGGER append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON position_ledger EXECUTE FUNCTION reject_modification();
CREATE TRIGGER append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON execution EXECUTE FUNCTION reject_modification();
CREATE TRIGGER append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON audit_log EXECUTE FUNCTION reject_modification();
